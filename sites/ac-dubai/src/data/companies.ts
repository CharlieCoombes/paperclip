export function companiesInCategory(categorySlug: string) {
  return companies.filter((c) => c.categorySlugs.includes(categorySlug));
}

export function featuredCompanies(limit = 6) {
  return [...companies]
    .sort((a, b) => Number(b.featured) - Number(a.featured) || b.rating - a.rating)
    .slice(0, limit);
}

export function topRated(limit = 6) {
  return [...companies].sort((a, b) => b.rating - a.rating).slice(0, limit);
}
